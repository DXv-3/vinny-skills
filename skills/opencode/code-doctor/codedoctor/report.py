"""Phase 6: REVIEW — generate the markdown report from session state."""

import os
from datetime import date

SEVERITY_LABELS = ("critical", "functional", "quality")


def _finding_line(f):
    return "- %s:%d — [%s] %s: %s" % (
        f["file"], f["line"], f["severity"], f["rule_id"], f["message"],
    )


def generate_report(state, project_name=None):
    profile = state.profile or {}
    counts = state.severity_counts()
    total = sum(counts.values())
    name = project_name or os.path.basename(state.project_path)

    langs = ", ".join(profile.get("languages", [])) or "(none detected)"
    lines = [
        "## Code Review: %s" % name,
        "",
        "### Profile",
        "- Project type: %s" % profile.get("project_type", "(unknown)"),
        "- Languages: %s" % langs,
        "- Scope: %s (%s read)" % (profile.get("file_count", 0), profile.get("scope", "?")),
        "",
        "### Files reviewed: %s" % (
            len(state.manifest_entries) if state.manifest_entries is not None else 0
        ),
        "### Issues found: %d (%d critical, %d functional, %d quality)" % (
            total, counts["critical"], counts["functional"], counts["quality"],
        ),
        "### Issues fixed: 0",
        "### Files edited: (none yet)",
    ]

    na = profile.get("na_flags") or []
    if na:
        lines.append("### N/A items:")
        lines.extend("- %s" % flag for flag in na)
    else:
        lines.append("### N/A items: none")

    for sev in SEVERITY_LABELS:
        group = [f for f in state.findings if f["severity"] == sev]
        header = {
            "critical": "Critical fixes:",
            "functional": "Functional fixes:",
            "quality": "Quality fixes:",
        }[sev]
        lines.append("")
        lines.append("### %s" % header)
        if not group:
            lines.append("- none found by static rules")
            continue
        for f in sorted(group, key=lambda x: (x["file"], x["line"])):
            lines.append(_finding_line(f))
            lines.append("  → fix applied: (pending agent review)")

    lines.extend([
        "",
        "### Deferred: (list with reasons)",
        "",
        "### Smoke test: BLOCKED — not run; execute one core user action manually",
        "",
        "### Unfixable architectural issues: (list)",
        "",
        "---",
        "_Generated by Code Doctor on %s from phases: %s_" % (
            date.today().isoformat(), ", ".join(state.phases_done) or "(none)"
        ),
    ])
    return "\n".join(lines)
